// The list form makes you learn "Zoology = the study of animals" and
// "Zoologist = one who studies animals" as two separate facts. They are one
// fact. Put the stem in the left column and every form built on it in the
// columns beside it, and one row teaches you three or four words.
//
// This is a VIEW of the same vocabulary as data/oneWord.ts, not a replacement —
// that file is still the practice generator's source. Here the organising idea
// is the shared stem; there it is the exam's distractor set.
//
// "—" means no standard word exists for that cell. Never invent one to fill a
// gap; a made-up word in a revision table is worse than a blank.

